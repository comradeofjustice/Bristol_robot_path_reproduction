"""Generate/check the Arduino header from the Processing trajectory CSV."""
import argparse
import csv
import re
from pathlib import Path

root = Path(__file__).resolve().parent
with (root / "PathTwin/data/path.csv").open(newline="") as f:
    rows = [(r["name"], *(int(r[k]) for k in ("duration_ms", "left_pwm", "right_pwm")))
            for r in csv.DictReader(f)]
names = [r[0] for r in rows]
assert rows and len(set(names)) == len(names) and "done" not in names
assert all(re.fullmatch(r"[a-z0-9_]+", n) and d > 0 and d % 50 == 0
           and max(abs(l), abs(r)) <= 120 for n, d, l, r in rows)
assert rows[-1][2:] == (0, 0) and sum(r[1] for r in rows) <= 30000
body = "".join(f'  {{"{n}", {d}, {l}, {r}}},\n' for n, d, l, r in rows)
header = (
    "#pragma once\n// Generated by sync_plan.py from PathTwin/data/path.csv.\n"
    "struct Segment { const char* name; uint32_t duration; int16_t left, right; };\n"
    "constexpr Segment PATH[] = {\n" + body + "};\n"
    f"constexpr uint32_t PATH_DURATION_MS = {sum(r[1] for r in rows)};\n"
    "constexpr size_t PATH_COUNT = sizeof(PATH) / sizeof(PATH[0]);\n"
)
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
path = root / "PathRobot/PathPlan.h"
if parser.parse_args().check:
    if path.read_text() != header:
        raise SystemExit("PathPlan.h is out of sync; run sync_plan.py")
else:
    path.write_text(header)
